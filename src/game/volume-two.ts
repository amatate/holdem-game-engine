export function volumeTwoNode(state:StoryState):StoryNode {
  const script=scripts[state.scene];
  if(!script)throw new Error(`Unknown Volume Two scene ${state.scene}`);
  return {
    night:script.night,title:script.title,en:script.title,location:script.location,
    lines:typeof script.lines==='function'?script.lines(state):script.lines,
    choices:typeof script.choices==='function'?script.choices(state):script.choices,
    task:script.task,taskEn:script.task,
  };
}
