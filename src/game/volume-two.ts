type Text = NightLine[] | ((state: StoryState) => NightLine[]);
type Choices = StoryChoice[] | ((state: StoryState) => StoryChoice[]);
type Script = { night:number; title:string; location:StoryLocation; lines:Text; choices:Choices; task:string };
const scripts:Record<string,Script> = {};
const flag = (s:StoryState,k:string) => s.flags[k] === true;
const endOfFirst = (s:StoryState) => [...s.history].reverse().find(h => h.scene.startsWith('v-end-'))?.scene ?? 'v-end-leave';
const wasInside = (s:StoryState) => ['v-end-stay','v-end-conditions-room'].includes(endOfFirst(s));
const personalContact = (s:StoryState) => flag(s,'w-contact-kai');
const promise = (s:StoryState) => s.source.route === 'new' && flag(s,'money-promise') && !flag(s,'no-money');
const owed = (s:StoryState) => flag(s,'kai-paid') ? 2850 : 3000;
const result = (s:StoryState,id:string) => s.results.find(r => r.id === id);
const lines = (...text:string[]):NightLine[] => text.map(text => {
  const match = text.match(/^(你|阿凯|莫叔|林岚|程墨|韩烈|苏蔓|老周)：(.*)$/s);
  return { who:match?.[1] ?? '', text:match?.[2] ?? text, en:match?.[2] ?? text };
});
const go = (to:string,text='继续',set?:Record<string,boolean>):StoryChoice => ({ id:to, text, en:text, to, ...(set ? {set} : {}) });
const play = (id:string,text:string):StoryChoice => ({id,text,en:text,table:id});
const record = (choice:StoryChoice,id:string,source:string,text:string):StoryChoice => ({...choice,fact:{id,source,text,en:text}});
const finish = ():StoryChoice => ({id:'finish',text:'保存第二卷结尾',en:'Save Volume Two ending',end:true});
function scene(id:string,night:number,title:string,location:StoryLocation,text:Text,choices:Choices,task:string) {
  scripts[id] = {night,title,location,lines:text,choices,task};
}

